/** Where an agent may never write: tool config, git internals, job state, and everything protected. */
const NO_WRITE: readonly string[] = [
  "**/.claude/**",
  "**/.kiro/**",
  "**/.opencode/**",
  "**/.git/**",
  "**/.adadex/**/job.json",
  "**/.adadex/**/audit.log",
  "**/.adadex/**/config.json",
  // The floor is relative to the repo. A write is checked by absolute path, so match it in any folder.
  // The job state folders are not blocked wholesale: an agent must write its stage documents there. What it may
  // write is scoped per role (see policyForRole), and the app's own files in it are always protected.
  ...PROTECTED_FLOOR.filter((p) => !p.includes("/factory/")).map((p) =>
    p.startsWith("**/") ? p : `**/${p}`,
  ),
];

/** The policy for review and read-only work. */
export const REVIEW_POLICY: PolicyRules = {
  allow: ALLOW,
  deny: DENY,
  ask: ASK,
  noWrite: NO_WRITE,
  writeOnly: [],
};

/** The policy for building: the review policy plus formatters and fixers that rewrite files. */
export const BUILD_POLICY: PolicyRules = { ...REVIEW_POLICY, allow: [...ALLOW, ...BUILD_ALLOW] };
